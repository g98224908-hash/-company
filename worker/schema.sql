CREATE TABLE IF NOT EXISTS roles (id TEXT PRIMARY KEY, active INTEGER DEFAULT 1, votes INTEGER DEFAULT 0, hits INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS jobs (
  id INTEGER PRIMARY KEY AUTOINCREMENT, url TEXT UNIQUE, repo TEXT, title TEXT, body TEXT,
  amount REAL DEFAULT 0, created_gh TEXT, comments INTEGER DEFAULT 0, status TEXT, score REAL,
  verdicts TEXT DEFAULT '{}', result TEXT, created_at TEXT, updated_at TEXT);
CREATE TABLE IF NOT EXISTS ledger (id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT, kind TEXT, amount REAL, note TEXT);
CREATE TABLE IF NOT EXISTS lessons (id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT, text TEXT);
